/**
 * Writes modules/ai-tools/render/katexAssets.generated.js: KaTeX's stylesheet with its fonts inlined
 * (base64 woff2), so an exported HTML document renders its formulas with no network and no files
 * next to it. Run it after upgrading `katex`:
 *
 *   node apps/web/scripts/generate-katex-assets.mjs
 *
 * Only the fonts formulas realistically use are kept (roman, bold, italic, math italic, AMS symbols,
 * the four delimiter sizes, calligraphic, sans, typewriter).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const dist = path.join(path.dirname(require.resolve("katex/package.json")), "dist");
const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, "..", "modules", "ai-tools", "render", "katexAssets.generated.js");

const KEEP = ["Main-Regular", "Main-Bold", "Main-Italic", "Main-BoldItalic", "Math-Italic", "Math-BoldItalic", "AMS-Regular", "Size1-Regular", "Size2-Regular", "Size3-Regular", "Size4-Regular", "Caligraphic-Regular", "SansSerif-Regular", "Typewriter-Regular"];

const css = readFileSync(path.join(dist, "katex.min.css"), "utf8");
const faces = [...css.matchAll(/@font-face\{[^}]*\}/g)].map((match) => match[0]);
const rules = css.replace(/@font-face\{[^}]*\}/g, "");
const fonts = {};
const faceRules = {};
for (const face of faces) {
  const file = /url\(fonts\/(KaTeX_[A-Za-z0-9-]+)\.woff2\)/.exec(face)?.[1];
  if (!file || !KEEP.includes(file.replace(/^KaTeX_/, ""))) continue;
  const family = /font-family:([^;]+);/.exec(face)?.[1];
  const style = /font-style:([^;]+);/.exec(face)?.[1];
  const weight = /font-weight:([^;]+);/.exec(face)?.[1];
  fonts[file] = readFileSync(path.join(dist, "fonts", `${file}.woff2`)).toString("base64");
  faceRules[file] = `@font-face{font-display:block;font-family:${family};font-style:${style};font-weight:${weight};src:url(data:font/woff2;base64,__DATA__) format("woff2")}`;
}

const lines = [
  "// GENERATED by apps/web/scripts/generate-katex-assets.mjs from katex@" + JSON.parse(readFileSync(path.join(dist, "..", "package.json"), "utf8")).version + " (MIT). Do not edit.",
  `export const KATEX_RULES = ${JSON.stringify(rules)};`,
  "/** font file → @font-face rule with the font inlined. */",
  "export const KATEX_FACES = {",
  ...Object.keys(fonts).map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(faceRules[file].replace("__DATA__", fonts[file]))},`),
  "};",
  ""
];
writeFileSync(target, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), target)} (${Math.round(lines.join("\n").length / 1024)} KB, ${Object.keys(fonts).length} fonts)`);
